"""Canonical P1 threat catalog. Loader writes these to threats/*.yaml."""

from __future__ import annotations

from typing import Any

from app.threats.schema import MutationParams


def _m(**kwargs: Any) -> dict[str, Any]:
    return MutationParams(**kwargs).model_dump()


def _threat(
    attack_id: str,
    name: str,
    family: str,
    category: str,
    objective: str,
    surface: list[str],
    signals: list[str],
    mitigation: str,
    mutation_strategy: str,
    difficulties: dict[str, dict[str, Any]],
    variants: list[tuple[str, str, dict[str, Any]]],
    *,
    network: str = "none",
    intent: str = "none",
    agent: str = "none",
    evasion: list[str] | None = None,
    entities: list[str] | None = None,
    features: list[str] | None = None,
) -> dict[str, Any]:
    return {
        "attack_id": attack_id,
        "name": name,
        "category": category,
        "evidence_level": "research_pattern",
        "objective": objective,
        "target": "normal_customers",
        "attack_surface": surface,
        "required_entities": entities or ["customer", "device", "merchant"],
        "required_features": features or ["amount", "hour_of_day", "transaction_count_24h"],
        "mutation_strategy": mutation_strategy,
        "network_strategy": network,
        "intent_strategy": intent,
        "agent_strategy": agent,
        "evasion_strategies": evasion or ["behavioral_mimicry"],
        "difficulty_levels": difficulties,
        "simulation_template": f"legit_overlay:{family}",
        "detection_signals": signals,
        "expected_mitigation": mitigation,
        "family": family,
        "variants": [{"id": vid, "name": vname, "overlays": ov} for vid, vname, ov in variants],
    }


